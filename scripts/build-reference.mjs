// Development-time step: turn a Facilio org package (folder or ZIP contents) into the bundled reference configuration.
// Usage: node scripts/build-reference.mjs <extracted-package-dir>
// Personal data is removed: people, users, emails, phone numbers and party contact names are not included.
import fs from 'node:fs'; import path from 'node:path'; import zlib from 'node:zlib'; import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { DOMParser } = require('@xmldom/xmldom');
const P = require('../src/parser.js');
const dir = process.argv[2]; if (!dir) { console.error('usage: build-reference.mjs <package-dir>'); process.exit(1); }
const files = {};
(function walk(d, rel) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f), r = rel ? rel + '/' + f : f; if (fs.statSync(p).isDirectory()) walk(p, r); else if (/\.xml$/i.test(f)) files[r] = fs.readFileSync(p, 'utf8'); } })(dir, '');
const b = P.parsePackage(files, { DOMParser, sourceName: 'Facilio reference org package' });
// ---- sanitise personal data
const party = list => list.map((x, i) => ({ name: x.name, deleted: x.deleted, ref: x.ref }));
b.vendors = party(b.vendors); b.tenants = party(b.tenants); b.clients = party(b.clients);
b.teams = b.teams.map(t => ({ name: t.name, members: t.members, active: t.active, ref: t.ref }));
const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, PHONE = /\+?\d[\d\s-]{8,}\d/g;
const scrub = o => { if (typeof o === 'string') return o.replace(EMAIL, '[email removed]'); if (Array.isArray(o)) return o.map(scrub); if (o && typeof o === 'object') { const r = {}; for (const k of Object.keys(o)) r[k] = scrub(o[k]); return r; } return o; };
const clean = scrub(b);
const text = JSON.stringify(clean);
const leaks = (text.match(EMAIL) || []).length;
if (leaks) { console.error('email addresses still present', leaks); process.exit(2); }
const gz = zlib.gzipSync(Buffer.from(text), { level: 9 });
const meta = { orgId: clean.meta.orgId, packageName: clean.meta.packageName, exportTimestamp: clean.meta.exportTimestamp, builtAt: new Date().toISOString(), modules: Object.keys(clean.modules).length, bytes: text.length, gzBytes: gz.length };
fs.writeFileSync(new URL('../server/reference-data.mjs', import.meta.url), `// Generated by scripts/build-reference.mjs — sanitised Facilio reference configuration (gzip, base64). Do not edit.\nexport const REFERENCE_META = ${JSON.stringify(meta)};\nexport const REFERENCE_GZ_B64 = ${JSON.stringify(gz.toString('base64'))};\n`);
console.log('reference written', meta);
